export const saveMaintenanceRecord = async ({ adminId, vehicle, form, activeAssignments = [] }) => {
  if (!vehicle?.id) throw new Error("Select a vehicle first.");
  if (!Object.values(VEHICLE_MAINTENANCE_STATUSES).includes(form.status)) throw new Error("Choose a supported maintenance status.");
  if (!hasText(form.maintenanceType, 2) || !hasText(form.description, 3)) throw new Error("Maintenance type and description are required.");
  if (form.status === VEHICLE_MAINTENANCE_STATUSES.COMPLETED && !form.completedAt) throw new Error("A completed maintenance record needs a completion date.");
  const assignmentConflict = activeAssignments.some((assignment) => assignment.vehicleId === vehicle.id && isActiveMission(assignment));
  if ([VEHICLE_MAINTENANCE_STATUSES.SCHEDULED, VEHICLE_MAINTENANCE_STATUSES.IN_PROGRESS].includes(form.status) && assignmentConflict) throw new Error("Resolve the active vehicle mission before starting maintenance.");
  const maintenanceRef = doc(collection(db, FIRESTORE_COLLECTIONS.VEHICLE_MAINTENANCE));
  await runTransaction(db, async (transaction) => {
    const vehicleRef = doc(db, FIRESTORE_COLLECTIONS.VEHICLES, vehicle.id);
    const vehicleSnapshot = await transaction.get(vehicleRef);
    if (!vehicleSnapshot.exists()) throw new Error("This vehicle no longer exists.");
    transaction.set(maintenanceRef, { vehicleId: vehicle.id, maintenanceType: form.maintenanceType.trim(), description: form.description.trim(), reportedIssues: form.reportedIssues.trim(), serviceProvider: form.serviceProvider.trim(), cost: Number(form.cost) || 0, odometer: form.odometer.trim(), status: form.status, startedAt: form.startedAt || null, completedAt: form.completedAt || null, nextServiceDate: form.nextServiceDate || null, createdBy: adminId, createdAt: serverTimestamp(), updatedAt: serverTimestamp() });
    const activeMaintenance = [VEHICLE_MAINTENANCE_STATUSES.SCHEDULED, VEHICLE_MAINTENANCE_STATUSES.IN_PROGRESS, VEHICLE_MAINTENANCE_STATUSES.REPORTED].includes(form.status);
    transaction.update(vehicleRef, { maintenanceStatus: form.status, status: activeMaintenance ? "Under Maintenance" : vehicleSnapshot.data().status || "Inactive", lastMaintenanceDate: form.completedAt || null, nextMaintenanceDate: form.nextServiceDate || null, updatedAt: serverTimestamp() });
    writeActivity(transaction, adminId, "vehicle-maintenance-created", "vehicle", vehicle.id, `Maintenance record added for ${vehicleSnapshot.data().name || vehicle.id}.`, { maintenanceStatus: form.status });
  });
};

export const saveSystemSettings = async ({ adminId, settings }) => {
  const allowedBarangays = [...new Set((settings.supportedBarangays || []).filter(Boolean))];
  const categories = [...new Set((settings.requestCategories || []).filter((item) => hasText(item, 2)))];
  const vehicleTypes = [...new Set((settings.vehicleTypes || []).filter((item) => hasText(item, 2)))];
  if (!hasText(settings.publicOfficePhone, 7)) throw new Error("Enter a public office phone number.");
  await setDoc(doc(db, FIRESTORE_COLLECTIONS.SYSTEM_SETTINGS, "operational"), { supportedBarangays: allowedBarangays, requestCategories: categories, vehicleTypes, publicOfficePhone: settings.publicOfficePhone.trim(), maintenanceReminderDays: Math.max(1, Number(settings.maintenanceReminderDays) || 30), updatedAt: serverTimestamp(), updatedBy: adminId }, { merge: true });
};